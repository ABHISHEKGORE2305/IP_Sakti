// src/lib/caseBrief.js
// Builds the Phase 5.4 "AYURVEDA IPR CASE BRIEF" from real wizard state +
// backend result (never fabricated placeholder data), and exports it as
// Markdown, JSON, or a printable view (for "Save as PDF").

function today() {
  return new Date().toISOString().slice(0, 10);
}

function line(label, value) {
  return value ? `* **${label}**: ${value}` : null;
}

/**
 * @param {object} wizard - { jurisdiction, classification, issue, targetMarket, query }
 * @param {object} result - the /api/agent response
 */
export function buildCaseBriefMarkdown(wizard, result) {
  const classification = wizard?.classificationResult?.classifier;
  const sections = [];

  sections.push('# AYURVEDA IPR CASE BRIEF');
  sections.push(`**Generated by IP-Sakti** | Date: ${today()}`);
  sections.push('');

  sections.push('### 1. Query & Jurisdiction');
  sections.push(
    [
      line('Question', wizard?.query),
      line('Jurisdiction', wizard?.jurisdiction),
      wizard?.targetMarket ? line('Target Market', wizard.targetMarket) : null,
      line('Specialist Agent', (result?.selected_agents || []).join(', ')),
    ]
      .filter(Boolean)
      .join('\n')
  );
  sections.push('');

  if (classification) {
    sections.push('### 2. Statutory Product Classification');
    sections.push(
      [
        line('Classified Category', classification.label),
        line('Statutory Basis', classification.statutory_basis),
        line('Primary Regulator', classification.primary_regulator),
        line('Clinical Evidence', classification.clinical_evidence),
        line('ABS/Biodiversity Triggers', classification.abs_biodiversity_triggers),
      ]
        .filter(Boolean)
        .join('\n')
    );
    if (classification.licensing_route?.length) {
      sections.push('');
      sections.push('**Licensing Route:**');
      classification.licensing_route.forEach((r) => sections.push(`- [ ] ${r}`));
    }
    sections.push('');
  }

  sections.push('### 3. Analysis');
  sections.push(result?.final_answer || '_No answer generated._');
  sections.push('');

  if (result?.sources?.length) {
    sections.push('### 4. Authoritative Sources & Citations');
    result.sources.forEach((s, i) => {
      const bits = [s.document, s.legal_reference, s.page != null ? `p.${s.page}` : null].filter(Boolean);
      sections.push(`${i + 1}. ${bits.join(', ')}`);
    });
    sections.push('');
  }

  if (result?.confidence) {
    sections.push('### 5. Confidence & Disclaimer');
    sections.push(
      `* **Confidence Band**: ${result.confidence.band} (score: ${
        typeof result.confidence.confidence === 'number' ? result.confidence.confidence.toFixed(2) : 'n/a'
      })`
    );
    if (result.citations) {
      sections.push(
        `* **Citation Verification**: ${result.citations.verified_citations}/${result.citations.total_citations} verified`
      );
    }
    sections.push(
      '* This brief is informational only, grounded in retrieved statutory sources. It is not legal advice — consult an accredited IP professional before filing.'
    );
    sections.push('');
  }

  sections.push('### 6. Open Questions for IP Facilitator');
  sections.push('* [ ] Confirm all statutory citations above against the primary source text.');
  sections.push('* [ ] Review claim phrasing / filing strategy with a registered patent agent.');

  return sections.join('\n');
}

export function buildCaseBriefJson(wizard, result) {
  return {
    generated_by: 'IP-Sakti',
    generated_at: new Date().toISOString(),
    query: wizard?.query,
    jurisdiction: wizard?.jurisdiction,
    target_market: wizard?.targetMarket || null,
    selected_agents: result?.selected_agents || [],
    classification: wizard?.classificationResult?.classifier || null,
    final_answer: result?.final_answer || '',
    sources: result?.sources || [],
    confidence: result?.confidence || null,
    citations: result?.citations || null,
    engine_results: result?.engine_results || null,
  };
}

function downloadBlob(filename, content, type) {
  const blob = new Blob([content], { type });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  URL.revokeObjectURL(url);
}

export function downloadMarkdown(wizard, result) {
  downloadBlob(
    `ip-sakti-case-brief-${today()}.md`,
    buildCaseBriefMarkdown(wizard, result),
    'text/markdown;charset=utf-8'
  );
}

export function downloadJson(wizard, result) {
  downloadBlob(
    `ip-sakti-case-brief-${today()}.json`,
    JSON.stringify(buildCaseBriefJson(wizard, result), null, 2),
    'application/json;charset=utf-8'
  );
}

/**
 * "Download PDF" without a bundled PDF library or CDN dependency: opens a
 * print-formatted window and invokes the browser's native print dialog,
 * where the user picks "Save as PDF". This is the standard dependency-free
 * approach — it is NOT a server-rendered PDF.
 */
export function printCaseBrief(wizard, result) {
  const markdown = buildCaseBriefMarkdown(wizard, result);
  const html = markdown
    .split('\n')
    .map((l) => {
      if (l.startsWith('# ')) return `<h1>${l.slice(2)}</h1>`;
      if (l.startsWith('### ')) return `<h3>${l.slice(4)}</h3>`;
      if (l.startsWith('- [ ] ')) return `<div class="checklist-item">☐ ${l.slice(6)}</div>`;
      if (l.startsWith('* [ ] ')) return `<div class="checklist-item">☐ ${l.slice(6)}</div>`;
      if (l.startsWith('* ')) return `<div class="brief-line">${l.slice(2)}</div>`;
      if (/^\d+\.\s/.test(l)) return `<div class="brief-line">${l}</div>`;
      if (!l.trim()) return '<br/>';
      return `<p>${l}</p>`;
    })
    .join('\n');

  const win = window.open('', '_blank', 'width=800,height=1000');
  if (!win) return;

  win.document.write(`<!doctype html>
<html><head><title>IP-Sakti Case Brief</title>
<meta charset="utf-8" />
<style>
  body { font-family: Georgia, 'Cormorant Garamond', serif; max-width: 760px; margin: 40px auto; color: #1c1c1c; line-height: 1.6; }
  h1 { font-size: 1.6rem; border-bottom: 2px solid #2f9e6e; padding-bottom: 8px; }
  h3 { font-size: 1.1rem; margin-top: 24px; color: #2f9e6e; }
  .checklist-item { margin: 4px 0; }
  .brief-line { margin: 2px 0; }
  strong { color: #111; }
  @media print { body { margin: 0; } }
</style>
</head><body>${html}</body></html>`);
  win.document.close();
  win.focus();
  win.print();
}
