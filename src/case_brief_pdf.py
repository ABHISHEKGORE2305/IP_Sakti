"""
Render a generated case brief (markdown) into a PDF report.

Used by /api/escalate so the IP facilitator receives a formatted,
printable brief as an attachment rather than raw markdown in the message
body. Built on PyMuPDF's Story HTML layout engine, which is already a
dependency (pymupdf, used for corpus ingestion) — no extra PDF library.

The visual design mirrors the frontend's "Export PDF" print stylesheet
(lib/caseBrief.js printMarkdownDocument) so the emailed report and the
one the user saves from the browser look like the same document.
"""

import html as html_escape
import io
import re
from datetime import date

import pymupdf

# The markdown subset buildCaseBriefMarkdown()/buildAbsChecklistMarkdown()
# emit: headings, bullet/ordered/task lists, bold, italics, inline code.
_HEADING_RE = re.compile(r"^(#{1,4})\s+(.*)$")
_TASK_RE = re.compile(r"^[-*]\s+\[( |x|X)\]\s+(.*)$")
_BULLET_RE = re.compile(r"^[-*]\s+(.*)$")
_ORDERED_RE = re.compile(r"^(\d+)[.)]\s+(.*)$")

_PAGE_CSS = """
body { font-family: serif; font-size: 10pt; color: #1a1a18; }
h1 { font-size: 15pt; margin-top: 14pt; margin-bottom: 6pt; }
h2 { font-size: 13pt; margin-top: 13pt; margin-bottom: 5pt; }
h3 { font-size: 10.5pt; color: #1f6f4e; margin-top: 12pt; margin-bottom: 4pt; }
h4 { font-size: 10pt; margin-top: 10pt; margin-bottom: 4pt; }
p { margin-top: 0pt; margin-bottom: 6pt; line-height: 1.45; }
li { margin-bottom: 3pt; line-height: 1.4; }
.doc-title { font-size: 17pt; font-weight: bold; margin-bottom: 2pt; }
.byline { font-size: 8.5pt; color: #4a4a44; margin-bottom: 14pt; }
.rule { font-size: 1pt; color: #1f6f4e; margin-bottom: 10pt; }
.colophon { font-size: 8pt; color: #4a4a44; margin-top: 16pt; line-height: 1.4; }
code { font-family: monospace; font-size: 9pt; }
"""

_COLOPHON = (
    "Generated by IP-Sakti — an AI-assisted research aid for Ayurveda IPR and "
    "regulatory questions. Informational only; not legal advice. Verify every "
    "statutory citation against its primary source before relying on it."
)


def _inline(text: str) -> str:
    """Inline markdown -> HTML, on already-escaped text."""

    out = html_escape.escape(text, quote=False)
    out = re.sub(r"`([^`]+)`", r"<code>\1</code>", out)
    out = re.sub(r"\[([^\]]+)\]\(([^)\s]+)\)", r"\1 (\2)", out)
    out = re.sub(r"\*\*([^*]+)\*\*", r"<b>\1</b>", out)
    out = re.sub(r"(^|[\s(])\*([^*\n]+)\*(?=[\s).,;:]|$)", r"\1<i>\2</i>", out)
    out = re.sub(r"(^|[\s(])_([^_\n]+)_(?=[\s).,;:]|$)", r"\1<i>\2</i>", out)
    return out


def markdown_to_html(markdown: str) -> str:
    """Render the brief's markdown subset as the HTML Story lays out."""

    parts: list[str] = []
    list_tag: str | None = None

    def close_list() -> None:
        nonlocal list_tag
        if list_tag:
            parts.append(f"</{list_tag}>")
            list_tag = None

    def open_list(tag: str) -> None:
        nonlocal list_tag
        if list_tag != tag:
            close_list()
            parts.append(f"<{tag}>")
            list_tag = tag

    for raw_line in str(markdown or "").split("\n"):
        line = raw_line.rstrip()
        if not line.strip():
            close_list()
            continue

        heading = _HEADING_RE.match(line)
        if heading:
            close_list()
            level = len(heading.group(1))
            parts.append(f"<h{level}>{_inline(heading.group(2))}</h{level}>")
            continue

        task = _TASK_RE.match(line)
        if task:
            close_list()
            box = "☑" if task.group(1).strip() else "☐"
            parts.append(f"<p>{box} {_inline(task.group(2))}</p>")
            continue

        bullet = _BULLET_RE.match(line)
        if bullet:
            open_list("ul")
            parts.append(f"<li>{_inline(bullet.group(1))}</li>")
            continue

        ordered = _ORDERED_RE.match(line)
        if ordered:
            open_list("ol")
            parts.append(f"<li>{_inline(ordered.group(2))}</li>")
            continue

        close_list()
        parts.append(f"<p>{_inline(line)}</p>")

    close_list()
    return "\n".join(parts)


def build_case_brief_pdf(markdown: str, title: str = "IP-Sakti Case Brief") -> bytes:
    """
    Lay `markdown` out as an A4 PDF and return its bytes.

    The brief's first two lines are its title and byline (see
    buildCaseBriefMarkdown); they become the letterhead so the body does
    not repeat them.
    """

    lines = str(markdown or "").split("\n")
    doc_title = re.sub(r"^#\s+", "", lines[0]).strip() if lines else ""
    byline = lines[1].replace("**", "").strip() if len(lines) > 1 else ""
    body_markdown = "\n".join(lines[2:]) if len(lines) > 2 else ""

    if not doc_title:
        doc_title = title
    if not body_markdown.strip():
        body_markdown = markdown or ""

    html_doc = (
        "<html><body>"
        f'<p class="doc-title">{html_escape.escape(doc_title, quote=False)}</p>'
        + (f'<p class="byline">{html_escape.escape(byline, quote=False)}</p>' if byline else "")
        + markdown_to_html(body_markdown)
        + f'<p class="colophon">{html_escape.escape(_COLOPHON, quote=False)}</p>'
        "</body></html>"
    )

    story = pymupdf.Story(html=html_doc, user_css=_PAGE_CSS)
    mediabox = pymupdf.paper_rect("a4")
    where = mediabox + (56, 56, -56, -56)

    buffer = io.BytesIO()
    writer = pymupdf.DocumentWriter(buffer)
    more = 1
    while more:
        device = writer.begin_page(mediabox)
        more, _ = story.place(where)
        story.draw(device)
        writer.end_page()
    writer.close()

    return _optimise(buffer.getvalue())


def _optimise(pdf_bytes: bytes) -> bytes:
    """Subset the embedded fonts — Story embeds them whole, which turns a
    one-page brief into a ~500 KB email attachment."""

    try:
        with pymupdf.open(stream=pdf_bytes, filetype="pdf") as doc:
            doc.subset_fonts()
            return doc.tobytes(garbage=4, deflate=True)
    except Exception:  # noqa: BLE001 - an unsubsetted PDF is still a valid one
        return pdf_bytes


def case_brief_filename(prefix: str = "ip-sakti-case-brief") -> str:
    return f"{prefix}-{date.today().isoformat()}.pdf"
